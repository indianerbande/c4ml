const messages: Record<WorkbenchUiLanguage, WorkbenchMessages> = {
  de: germanMessages,
  en: englishMessages,
};

export type WorkbenchMessageParameters = Readonly<
  Record<string, string | number>
>;

export function workbenchMessage(
  language: WorkbenchUiLanguage,
  key: WorkbenchMessageKey,
  parameters: WorkbenchMessageParameters = {},
): string {
  let message: string = messages[language][key];
  for (const [name, value] of Object.entries(parameters)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}
